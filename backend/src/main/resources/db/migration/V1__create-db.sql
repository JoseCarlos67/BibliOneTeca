-- 1. TABELAS DE DOMÍNIO PRINCIPAL E CATÁLOGO

CREATE TABLE AUTHORS
(
    ID            VARCHAR(36) NOT NULL,
    NAME          VARCHAR(255) NOT NULL,
    DATE_OF_BIRTH DATE NOT NULL,
    DATE_OF_DEATH DATE,
    NATIONALITY   VARCHAR(255),
    CONSTRAINT PK_AUTHORS PRIMARY KEY (ID)
);

CREATE INDEX IDX_AUTHORS_NAME ON AUTHORS (NAME);


CREATE TABLE BOOKS
(
    ID    VARCHAR(36) NOT NULL,
    TITLE VARCHAR(255) NOT NULL,
    CONSTRAINT PK_BOOKS PRIMARY KEY (ID)
);

CREATE INDEX IDX_BOOKS_TITLE ON BOOKS (TITLE);


CREATE TABLE PUBLISHERS
(
    ID         VARCHAR(36) NOT NULL,
    LEGAL_NAME VARCHAR(255) NOT NULL,
    TRADE_NAME VARCHAR(255) NOT NULL,
    CNPJ       VARCHAR(14) NOT NULL,
    SITE_URL   VARCHAR(255),
    CONSTRAINT PK_PUBLISHERS PRIMARY KEY (ID),
    CONSTRAINT UK_PUBLISHERS_CNPJ UNIQUE (CNPJ)
);


CREATE TABLE EDITIONS
(
    ID               VARCHAR(36) NOT NULL,
    ISBN             VARCHAR(17) NOT NULL,
    FK_BOOK          VARCHAR(36) NOT NULL,
    FK_PUBLISHER     VARCHAR(36) NOT NULL,
    EDITION_NUMBER   INTEGER,
    YEAR_PUBLICATION INTEGER NOT NULL,
    LANGUAGE         VARCHAR(100) NOT NULL,
    PAGE_NUMBER      INTEGER NOT NULL,
    COVER            VARCHAR(255) NOT NULL,
    SYNOPSIS         TEXT NOT NULL,
    CONSTRAINT PK_EDITIONS PRIMARY KEY (ID),
    CONSTRAINT UK_EDITIONS_ISBN UNIQUE (ISBN)
);


CREATE TABLE GENRES
(
    ID   VARCHAR(36) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    CONSTRAINT PK_GENRES PRIMARY KEY (ID)
);

CREATE INDEX IDX_GENRES_NAME ON GENRES (NAME);


CREATE TABLE AUTHOR_BOOK
(
    FK_AUTHOR VARCHAR(36) NOT NULL,
    FK_BOOK   VARCHAR(36) NOT NULL,
    CONSTRAINT PK_AUTHOR_BOOK PRIMARY KEY (FK_AUTHOR, FK_BOOK)
);


CREATE TABLE BOOK_GENRE
(
    FK_BOOK  VARCHAR(36) NOT NULL,
    FK_GENRE VARCHAR(36) NOT NULL,
    CONSTRAINT PK_BOOK_GENRE PRIMARY KEY (FK_BOOK, FK_GENRE)
);


-- 2. TABELAS DE ATORES DO SISTEMA (USUÁRIOS)

CREATE TABLE CLIENTS
(
    ID                      VARCHAR(36) NOT NULL,
    CPF                     VARCHAR(11) NOT NULL,
    FULL_NAME               VARCHAR(255) NOT NULL,
    DATE_OF_BIRTH           DATE NOT NULL,
    EMAIL                   VARCHAR(255),
    CELL_NUMBER             VARCHAR(20) NOT NULL,
    REGISTRATION_EXPIRATION DATE NOT NULL,
    CONSTRAINT PK_CLIENTS PRIMARY KEY (ID),
    CONSTRAINT UK_CLIENTS_CPF UNIQUE (CPF),
    CONSTRAINT UK_CLIENTS_EMAIL UNIQUE (EMAIL)
);


CREATE TABLE LIBRARIANS
(
    ID            VARCHAR(36) NOT NULL,
    PASSWORD      VARCHAR(255) NOT NULL,
    FULL_NAME     VARCHAR(255) NOT NULL,
    DATE_OF_BIRTH DATE NOT NULL,
    CPF           VARCHAR(11) NOT NULL,
    EMAIL         VARCHAR(255) NOT NULL,
    CONSTRAINT PK_LIBRARIANS PRIMARY KEY (ID),
    CONSTRAINT UK_LIBRARIANS_CPF UNIQUE (CPF),
    CONSTRAINT UK_LIBRARIANS_EMAIL UNIQUE (EMAIL)
);


-- 3. TABELAS DE INVENTÁRIO FÍSICO E OPERACIONAL (EMPRÉSTIMOS)

CREATE TABLE PHYSICAL_COPIES
(
    ID         VARCHAR(36) NOT NULL,
    FK_EDITION VARCHAR(36) NOT NULL,
    ASSET_CODE VARCHAR(50) NOT NULL,
    STATUS     VARCHAR(20) DEFAULT 'AVAILABLE' NOT NULL,
    CONSTRAINT PK_PHYSICAL_COPIES PRIMARY KEY (ID),
    CONSTRAINT UK_PHYSICAL_ASSET_CODE UNIQUE (ASSET_CODE),
    CONSTRAINT CHK_PHYSICAL_STATUS CHECK (STATUS IN ('AVAILABLE', 'LOANED', 'LOST', 'MAINTENANCE'))
);


CREATE TABLE LOANS
(
    ID               VARCHAR(36) NOT NULL,
    FK_LIBRARIAN     VARCHAR(36) NOT NULL,
    FK_PHYSICAL_COPY VARCHAR(36) NOT NULL,
    FK_CLIENT        VARCHAR(36) NOT NULL,
    DATE_LOAN        DATE DEFAULT CURRENT_DATE NOT NULL,
    DUE_DATE         DATE NOT NULL,
    DATE_RETURN      DATE,
    RENEWAL          INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_LOANS PRIMARY KEY (ID)
);


-- ===================================================================
-- 4. CHAVES ESTRANGEIRAS (DEFERRABLE INITIALLY IMMEDIATE)
-- ===================================================================

ALTER TABLE EDITIONS
    ADD CONSTRAINT FK_EDITIONS_BOOK FOREIGN KEY (FK_BOOK)
        REFERENCES BOOKS (ID) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE EDITIONS
    ADD CONSTRAINT FK_EDITIONS_PUBLISHER FOREIGN KEY (FK_PUBLISHER)
        REFERENCES PUBLISHERS (ID) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE AUTHOR_BOOK
    ADD CONSTRAINT FK_AB_AUTHOR FOREIGN KEY (FK_AUTHOR)
        REFERENCES AUTHORS (ID) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE AUTHOR_BOOK
    ADD CONSTRAINT FK_AB_BOOK FOREIGN KEY (FK_BOOK)
        REFERENCES BOOKS (ID) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE BOOK_GENRE
    ADD CONSTRAINT FK_BG_BOOK FOREIGN KEY (FK_BOOK)
        REFERENCES BOOKS (ID) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE BOOK_GENRE
    ADD CONSTRAINT FK_BG_GENRE FOREIGN KEY (FK_GENRE)
        REFERENCES GENRES (ID) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE PHYSICAL_COPIES
    ADD CONSTRAINT FK_PHYSICAL_EDITION FOREIGN KEY (FK_EDITION)
        REFERENCES EDITIONS (ID) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE LOANS
    ADD CONSTRAINT FK_LOANS_LIBRARIAN FOREIGN KEY (FK_LIBRARIAN)
        REFERENCES LIBRARIANS (ID) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE LOANS
    ADD CONSTRAINT FK_LOANS_PHYSICAL_COPY FOREIGN KEY (FK_PHYSICAL_COPY)
        REFERENCES PHYSICAL_COPIES (ID) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE LOANS
    ADD CONSTRAINT FK_LOANS_CLIENT FOREIGN KEY (FK_CLIENT)
        REFERENCES CLIENTS (ID) DEFERRABLE INITIALLY IMMEDIATE;


